_OPEN = "<" * 7
_MID = "=" * 7
_CLOSE = ">" * 7
_SHORT_OPEN = "<" * 4
_SHORT_MID = "=" * 4
_SHORT_CLOSE = ">" * 4
_FENCE = "`" * 3

